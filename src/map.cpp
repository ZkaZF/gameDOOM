int isWalkable(float x, float y) {
    int lx = (int)(x / MAP_SCALE);
    int ly = (int)(y / MAP_SCALE);
    if (lx < 0 || lx >= MAP_LOGICAL_W || ly < 0 || ly >= MAP_LOGICAL_H) return 0;
    return worldMap[ly][lx] == 0;
}
